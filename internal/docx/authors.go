package docx

// AuthorFilterName is the file name of the generated author Lua filter.
const AuthorFilterName = "authors.lua"

// HasStructuredAuthors reports whether the author metadata holds an entry
// written as a map (name, affiliation, ...). The DOCX writer renders only
// plain-text authors and silently drops map entries.
func HasStructuredAuthors(meta map[string]any) bool {
	switch v := meta["author"].(type) {
	case map[string]any:
		return true
	case []any:
		for _, item := range v {
			if _, ok := item.(map[string]any); ok {
				return true
			}
		}
	}
	return false
}

// AuthorFilter is the source of a pandoc Lua filter that flattens
// structured authors into lines (name, affiliation, department, city and
// country, email), mirroring the LaTeX template's title block.
const AuthorFilter = `-- authors.lua, generated by lumina from metadata.yaml.
-- Flattens structured authors into inlines, one line per field, because the
-- DOCX writer drops author entries that are maps.

local function inlines(v)
  if v == nil then return nil end
  local t = pandoc.utils.type(v)
  if t == "string" then return pandoc.Inlines(v) end
  if t == "Blocks" then return pandoc.utils.blocks_to_inlines(v) end
  if t == "Inlines" then return v end
  return pandoc.Inlines(pandoc.utils.stringify(v))
end

local function flatten(a)
  if pandoc.utils.type(a) ~= "table" or a.name == nil then return a end

  local lines = {}
  local function add(l)
    if l ~= nil and #l > 0 then table.insert(lines, l) end
  end
  add(inlines(a.name))
  add(inlines(a.affiliation))
  add(inlines(a.department))
  local place = inlines(a.city)
  local country = inlines(a.country)
  if place ~= nil and country ~= nil then
    place = place .. pandoc.Inlines{pandoc.Str(","), pandoc.Space()} .. country
  end
  add(place or country)
  if a.email ~= nil then
    local email = pandoc.utils.stringify(a.email)
    add(pandoc.Inlines{pandoc.Link(email, "mailto:" .. email)})
  end

  local out = pandoc.Inlines{}
  for i, l in ipairs(lines) do
    if i > 1 then out:insert(pandoc.LineBreak()) end
    out:extend(l)
  end
  return out
end

function Meta(meta)
  if FORMAT ~= "docx" or meta.author == nil then return nil end
  local authors = meta.author
  if pandoc.utils.type(authors) ~= "List" then authors = pandoc.List{authors} end
  meta.author = authors:map(flatten)
  return meta
end
`
