package docx

import (
	"fmt"
	"strings"
)

// PageBreaksKey is the metadata key listing glob patterns for level-1
// headings that start a new page in DOCX output.
const PageBreaksKey = "pagebreak-before"

// PageBreakFilterName is the file name of the generated Lua filter.
const PageBreakFilterName = "pagebreaks.lua"

// PageBreaks lists where the DOCX output starts a new page.
type PageBreaks struct {
	// AfterTOC starts the body on a new page after the table of contents.
	AfterTOC bool
	// Before holds glob patterns matched against the text of level-1
	// headings.
	Before []string
}

// IsZero reports whether b requests no page breaks.
func (b PageBreaks) IsZero() bool {
	return !b.AfterTOC && len(b.Before) == 0
}

// PageBreaksFromMeta reads toc and pagebreak-before from pandoc metadata.
func PageBreaksFromMeta(meta map[string]any) (PageBreaks, error) {
	var b PageBreaks
	if toc, ok := meta["toc"].(bool); ok {
		b.AfterTOC = toc
	}

	switch v := meta[PageBreaksKey].(type) {
	case nil:
	case string:
		b.Before = []string{v}
	case []any:
		for _, item := range v {
			s, ok := item.(string)
			if !ok {
				return PageBreaks{}, fmt.Errorf("%s: expected a string, got %v", PageBreaksKey, item)
			}
			b.Before = append(b.Before, s)
		}
	default:
		return PageBreaks{}, fmt.Errorf("%s: expected a string or a list of strings, got %v", PageBreaksKey, v)
	}

	for _, glob := range b.Before {
		if _, err := globToLuaPattern(glob); err != nil {
			return PageBreaks{}, fmt.Errorf("%s: %w", PageBreaksKey, err)
		}
	}
	return b, nil
}

// pageBreakXML is an empty, 1pt high paragraph that starts a new page.
const pageBreakXML = `<w:p><w:pPr><w:pageBreakBefore/>` +
	`<w:spacing w:before="0" w:after="0" w:line="20" w:lineRule="exact"/>` +
	`<w:rPr><w:sz w:val="2"/></w:rPr></w:pPr></w:p>`

const pageBreakFilter = `-- pagebreaks.lua, generated by lumina from metadata.yaml.
-- Inserts DOCX page breaks before the body (after the table of contents)
-- and before matching level-1 headings.

local after_toc = %t
local patterns = {%s}
local page_break = pandoc.RawBlock("openxml", %s)

local function matches(el)
  if el.t ~= "Header" or el.level ~= 1 then return false end
  local text = pandoc.utils.stringify(el.content)
  for _, p in ipairs(patterns) do
    if text:match(p) then return true end
  end
  return false
end

function Pandoc(doc)
  if FORMAT ~= "docx" then return nil end
  local blocks = {}
  for i, el in ipairs(doc.blocks) do
    if (i == 1 and after_toc) or matches(el) then
      table.insert(blocks, page_break)
    end
    table.insert(blocks, el)
  end
  doc.blocks = blocks
  return doc
end
`

// Filter returns the source of a pandoc Lua filter that inserts the page
// breaks into DOCX output.
func (b PageBreaks) Filter() (string, error) {
	patterns := make([]string, 0, len(b.Before))
	for _, glob := range b.Before {
		p, err := globToLuaPattern(glob)
		if err != nil {
			return "", err
		}
		patterns = append(patterns, luaString(p))
	}
	return fmt.Sprintf(pageBreakFilter, b.AfterTOC, strings.Join(patterns, ", "), luaString(pageBreakXML)), nil
}

// utf8Char is a Lua pattern matching one UTF-8 encoded character.
const utf8Char = "[\x00-\x7F\xC2-\xFD][\x80-\xBF]*"

// globToLuaPattern converts a shell-style glob (* any text, ? one
// character, \ escapes the next character) into an anchored Lua pattern.
func globToLuaPattern(glob string) (string, error) {
	var sb strings.Builder
	sb.WriteByte('^')
	for i := 0; i < len(glob); i++ {
		c := glob[i]
		switch c {
		case '*':
			sb.WriteString(".*")
		case '?':
			sb.WriteString(utf8Char)
		case '\\':
			i++
			if i == len(glob) {
				return "", fmt.Errorf("pattern %q ends with an escape character", glob)
			}
			writeLuaLiteral(&sb, glob[i])
		default:
			writeLuaLiteral(&sb, c)
		}
	}
	sb.WriteByte('$')
	return sb.String(), nil
}

func writeLuaLiteral(sb *strings.Builder, c byte) {
	if strings.IndexByte("^$()%.[]*+-?", c) >= 0 {
		sb.WriteByte('%')
	}
	sb.WriteByte(c)
}

// luaString quotes s as a Lua string literal, escaping control and
// non-ASCII bytes as decimal escapes.
func luaString(s string) string {
	var sb strings.Builder
	sb.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			sb.WriteByte('\\')
			sb.WriteByte(c)
		case c < 0x20 || c >= 0x7F:
			fmt.Fprintf(&sb, "\\%03d", c)
		default:
			sb.WriteByte(c)
		}
	}
	sb.WriteByte('"')
	return sb.String()
}
